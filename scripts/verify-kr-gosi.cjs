const normCas = (c) =>
  String(c || "")
    .split(/[\s,;/]+/)
    .map((s) => s.trim().replace(/\(.*$/, "").split("-").map((p) => p.replace(/^0+(?=\d)/, "")).join("-"))
    .filter(Boolean);

// 숫자 집합 추출(포맷 관용: 후행 0/소수점 정규화). "0.50"→"0.5", "1.0"→"1"
const numKey = (n) => {
  const f = parseFloat(n);
  return Number.isFinite(f) ? String(f) : null;
};
const numsIn = (s) => {
  const set = new Set();
  for (const m of String(s || "").matchAll(/\d+\.?\d*/g)) {
    const k = numKey(m[0]);
    if (k) set.add(k);
  }
  return set;
};

function main() {
  const strict = process.argv.includes("--strict");
  const ings = JSON.parse(fs.readFileSync(path.join(DATA, "ingredients.json"), "utf8")).rows;
  const kr = JSON.parse(fs.readFileSync(path.join(DATA, "regulations", "KR.json"), "utf8")).rows;

  // CAS(정규화) → ingredient id 들
  const casToIds = new Map();
  for (const i of ings) for (const c of normCas(i.cas_no)) (casToIds.get(c) || casToIds.set(c, []).get(c)).push(i.id);
  const rowsById = new Map();
  for (const r of kr) (rowsById.get(r.ingredient_id) || rowsById.set(r.ingredient_id, []).get(r.ingredient_id)).push(r);
  const nk = (s) => String(s || "").replace(/[\s()\-,'·]/g, "");

  const misses = [];
  for (const [cas, name, limits, cat, alias] of GOSI) {
    const ids = new Set();
    for (const c of normCas(cas)) for (const id of casToIds.get(c) || []) ids.add(id);
    // CAS 가 메인 엔트리에 없거나(IPBC=None) 별표가 cis-form 등 다른 번호를 든 경우(쿼터늄-15) 이름 폴백.
    // CAS 가 0행 엔트리에만 걸린 경우도 있어 항상 합집합으로 보강.
    if (alias) {
      const a = nk(alias);
      for (const i of ings)
        if (i.korean_name && (rowsById.get(i.id) || []).length && (nk(i.korean_name) === a || nk(i.korean_name).includes(a) || a.includes(nk(i.korean_name)))) ids.add(i.id);
    }
    if (!ids.size) {
      misses.push({ cas, name, cat, reason: "성분 없음(CAS 미존재)", need: limits });
      continue;
    }
    const present = new Set();
    let hasRow = false;
    for (const id of ids)
      for (const r of rowsById.get(id) || []) {
        hasRow = true;
        for (const n of numsIn(r.conditions)) present.add(n);
        if (r.max_concentration != null) { const k = numKey(r.max_concentration); if (k) present.add(k); }
      }
    if (!hasRow) {
      misses.push({ cas, name, cat, reason: "KR 규제행 없음", need: limits });
      continue;
    }
    // 대표 한도(첫 값)가 표면화되어야 함
    const primary = numKey(limits[0]);
    if (primary && !present.has(primary))
      misses.push({ cas, name, cat, reason: `한도 ${limits[0]}% 미표면화`, need: limits, present: [...present].slice(0, 10) });
  }

  // ── 별표1 사용금지 원료 검증 ── MFDS 자동데이터가 KR 금지행을 누락했던(검색 시 false-allowed)
  // 무조건 금지물질. 고시 별표1 직접 대조로 확정·override 보강한 건들이 banned 로 표면화되는지 확인.
  // (조건부 금지[염모제 제외·과산화물가 초과]는 restricted 가 정당하므로 제외 — 분별력)
  const GOSI_BANNED = [
    "110-71-4", "112-34-5", "1150-90-9", "1404-88-2", "1480-19-9", "2451-62-9",
    "24828-38-4", "2748-74-5", "57-63-6", "5934-19-0", "8023-88-9", "84777-06-0",
    "84961-56-8", "89997-54-6", "90106-13-1", "97-77-8",
  ];
  for (const cas of GOSI_BANNED) {
    const ids = new Set();
    for (const c of normCas(cas)) for (const id of casToIds.get(c) || []) ids.add(id);
    if (!ids.size) { misses.push({ cas, name: "(별표1 금지)", cat: "사용금지", reason: "성분 없음" }); continue; }
    let banned = false;
    for (const id of ids) for (const r of rowsById.get(id) || []) if (r.status === "banned") banned = true;
    if (!banned) misses.push({ cas, name: "(별표1 금지)", cat: "사용금지", reason: "banned 미표면화(false-allowed)" });
  }

  const report = { generated_for: "KR 화장품 안전기준 별표1(금지)·별표2(자외선차단·보존제) 고시 대조", total: GOSI.length + GOSI_BANNED.length, missing: misses.length, misses };
  let prev = null;
  try { prev = JSON.parse(fs.readFileSync(REPORT, "utf8")); } catch {}
  fs.writeFileSync(REPORT, JSON.stringify(report, null, 2), "utf8");

  console.log(`verify-kr-gosi: ${GOSI.length + GOSI_BANNED.length}종 검사(별표2 한도 ${GOSI.length} + 별표1 금지 ${GOSI_BANNED.length}), 누락 ${misses.length}건`);
  for (const m of misses) console.log(`  ⚠ [${m.cat}] ${m.name} (${m.cas}) — ${m.reason}`);

  const prevN = prev ? prev.missing : 0;
  if (strict && misses.length > prevN) {
    console.error(`❌ 회귀: 고시 대조 누락 ${prevN} → ${misses.length} (신규 ${misses.length - prevN}건). limit-overrides.json 로 보강 필요.`);
    process.exit(1);
  }
}
main();
