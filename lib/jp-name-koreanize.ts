// 카나 받침(ン) 합성: 앞 음절에 ㄴ 받침을 붙인다.
function applyNasal(syllables: string[]): string {
  let out = "";
  for (const s of syllables) {
    if (s === "ㄴ") {
      // 앞 한글 음절에 받침 ㄴ 추가(종성 없는 경우만; 있으면 '느'로 분리)
      const last = out.slice(-1);
      const code = last.charCodeAt(0);
      if (last >= "가" && last <= "힣" && (code - 0xac00) % 28 === 0) {
        out = out.slice(0, -1) + String.fromCharCode(code + 4); // +ㄴ 종성
      } else {
        out += "ㄴ";
      }
    } else {
      out += s;
    }
  }
  return out;
}

function translitKana(s: string): string {
  // 히라가나 → 카타카나 정규화(ぁ-ゖ → ァ-ヶ, +0x60)
  s = s.replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60));
  const syl: string[] = [];
  for (let i = 0; i < s.length; i++) {
    const two = s.slice(i, i + 2);
    if (YOON[two]) { syl.push(YOON[two]); i++; continue; }
    const ch = s[i];
    if (KANA[ch] !== undefined) { syl.push(KANA[ch]); continue; }
    syl.push(ch); // 비카나(영숫자·기호)는 그대로
  }
  return applyNasal(syl);
}

