const HAS_CJK = /[぀-ヿ㐀-鿿]/;
const HAS_KANA = /[ぁ-んァ-ヶ]/;
const LATIN_RUN = /[A-Za-z]{3,}/;

// 라틴+CJK: CJK 괄호/후행 조항을 제거해 깨끗한 영문명을 얻는다(영어는 허용).
function stripCJKFromLatin(s: string): string {
  return s
    .replace(/[（(][^（()）]*[）)]/g, (m) => (HAS_CJK.test(m) ? "" : m)) // CJK 든 괄호 제거
    .replace(/[\s,，、]*[一-鿿぀-ヿ][一-鿿぀-ヿ・，、。\s/／]*$/u, "")       // 후행 CJK 조항(+꼬리부호)
    .replace(/\s{2,}/g, " ")
    .trim();
}

/**
 * 성분명을 표시용으로 한글화. CJK 없으면 그대로 반환.
 * 반환: { name: 표시명(제목), isKorean: 한글본체로 바뀌었나 }
 */
export function koreanizeName(input: string): { name: string; isKorean: boolean } {
  // NFKC: CJK 호환 한자(U+F900-FAFF, 예 狀=U+F9FA)·전각부호를 정규형으로. 미정규화 시
  // 한자 사전(정규 U+72C0 기준)이 호환 코드포인트를 못 잡아 잔존.
  const s = (input || "").normalize("NFKC").trim();
  if (!s || !HAS_CJK.test(s)) return { name: s, isKorean: false };

  // ① 라틴 본체 충분 + CJK 가 괄호/후행에만 → 영문명으로 정리
  const latinCount = (s.match(/[A-Za-z]/g) || []).length;
  if (LATIN_RUN.test(s) && latinCount >= 3) {
    const cleaned = stripCJKFromLatin(s);
    if (cleaned && !HAS_CJK.test(cleaned)) return { name: cleaned, isKorean: false };
    // 괄호 strip 후에도 CJK 잔존 시 아래 한글화로 진행
  }

  // ②③ CJK 본체 → 형태소 사전 → 한자 → 카나 음역
  let out = s;
  for (const [ja, ko] of MORPHEME) {
    if (out.indexOf(ja) !== -1) out = out.split(ja).join(ko);
  }
  // 구분자/장음 정규화(카타카나 블록이라 잔존 오검출되는 ・ー 처리)
  out = out.replace(/・/g, "·").replace(/ー/g, "").replace(/／/g, "/")
    .replace(/、/g, ", ").replace(/。/g, ". ").replace(/「|」|『|』/g, "");
  // 잔존 한자 단독자
  out = out.replace(/[㐀-鿿]/g, (c) => KANJI1[c] ?? c);
  // 잔존 카나(히라+카타) 음역
  if (/[ぁ-んァ-ヶ]/.test(out)) out = translitKana(out);
  // 음역 후에도 남은 한자(사전 미스) 1자 처리
  out = out.replace(/[㐀-鿿]/g, (c) => KANJI1[c] ?? c);

  return { name: out, isKorean: true };
}
